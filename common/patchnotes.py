# 알림을 띄우는 종류. 설정에서 통째로 끌 수 있다(notifyImportant).
# **게임 안에서 일어나는 일은 여기 넣지 않는다.** 포켓몬을 잡을 때마다
# 화면 구석에서 알림이 튀어나오면 하던 일을 방해한다. 바탕화면에서 눈으로
# 보이는 것으로 충분하다. 여기 있는 둘은 화면에 아무 자국도 남지 않아서,
# 알려주지 않으면 알 길이 없는 것들이다.
TOAST_KINDS = ("update", "friend")


def entry(version):
    """그 버전의 묶음. 없으면 None."""
    for n in NOTES:
        if n["version"] == version:
            return n
    return None


def latest():
    return NOTES[0] if NOTES else None


def as_markdown(version):
    """릴리스 본문에 붙일 꼴. 없으면 빈 문자열."""
    n = entry(version)
    if not n:
        return ""
    out = []
    if n.get("headline"):
        out.append("### %s" % n["headline"])
        out.append("")
    for title, body in n["items"]:
        if body:
            out.append("- **%s** — %s" % (title, body))
        else:
            out.append("- **%s**" % title)
    return "\n".join(out) + "\n"
