def entry(version):
    """그 버전의 묶음. 없으면 None."""
    for n in NOTES:
        if n["version"] == version:
            return n
    return None


def latest():
    return NOTES[0] if NOTES else None


def _key(v):
    """버전을 견줄 수 있는 값으로. '1.1.10' 이 '1.1.9' 보다 커야 한다."""
    out = []
    for part in (v or "").split("."):
        try:
            out.append(int(part))
        except ValueError:
            out.append(0)
    return tuple(out)


def since(old, new):
    """old 다음부터 new 까지의 묶음을 **최신이 앞에** 오도록.

    1.0.1 을 쓰던 사람이 1.0.3 으로 갈아탔으면 1.0.3 과 1.0.2 를 준다 -
    건너뛴 판의 변경 내역도 읽을 수 있어야 한다. 예전에는 지금 판 하나만
    보여줘서, 이틀 만에 두 판이 나가면 가운데 판은 아무도 못 봤다.

    old 가 비어 있으면(처음 깐 사람) new 하나만 준다. 새로 깐 사람에게
    지난 판을 다 보여줄 이유가 없다.
    """
    hi = _key(new)
    if not old:
        one = entry(new)
        return [one] if one else []
    lo = _key(old)
    got = [n for n in NOTES if lo < _key(n["version"]) <= hi]
    got.sort(key=lambda n: _key(n["version"]), reverse=True)
    return got


def as_markdown(version):
    """릴리스 본문에 붙일 꼴. 없으면 빈 문자열."""
    n = entry(version)
    if not n:
        return ""
    out = []
    if n.get("headline"):
        out.append("### %s" % n["headline"])
        out.append("")
    for title, body in n["items"]:
        if body:
            out.append("- **%s** — %s" % (title, body))
        else:
            out.append("- **%s**" % title)
    return "\n".join(out) + "\n"
