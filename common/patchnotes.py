def entry(version):
    """그 버전의 묶음. 없으면 None."""
    for n in NOTES:
        if n["version"] == version:
            return n
    return None


def latest():
    return NOTES[0] if NOTES else None


def as_markdown(version):
    """릴리스 본문에 붙일 꼴. 없으면 빈 문자열."""
    n = entry(version)
    if not n:
        return ""
    out = []
    if n.get("headline"):
        out.append("### %s" % n["headline"])
        out.append("")
    for title, body in n["items"]:
        if body:
            out.append("- **%s** — %s" % (title, body))
        else:
            out.append("- **%s**" % title)
    return "\n".join(out) + "\n"
