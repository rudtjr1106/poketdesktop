# 알림을 띄우는 종류. 설정에서 통째로 끌 수 있다(notifyImportant).
# **게임 안에서 일어나는 일은 여기 넣지 않는다.** 포켓몬을 잡을 때마다
# 화면 구석에서 알림이 튀어나오면 하던 일을 방해한다. 바탕화면에서 눈으로
# 보이는 것으로 충분하다. 여기 있는 둘은 화면에 아무 자국도 남지 않아서,
# 알려주지 않으면 알 길이 없는 것들이다.
